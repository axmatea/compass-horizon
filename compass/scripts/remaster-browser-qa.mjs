import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';

const base=process.env.REMASTER_QA_URL||'http://localhost:8770';
const out=resolve('delivery/remaster/qa');await mkdir(out,{recursive:true});
const browser=await chromium.launch();
const report={at:new Date().toISOString(),base,checks:[],errors:[]};
const read=page=>page.evaluate(()=>JSON.parse(window.render_game_to_text()).snapshot);
const step=async(page,ms)=>{await page.evaluate(ms=>window.advanceTime(ms),ms);await page.waitForTimeout(80);};
const overflow=page=>page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
const open=async page=>{
  await page.goto(`${base}/demo/remaster?clock=manual`);
  await page.waitForFunction(()=>typeof window.render_game_to_text==='function'&&JSON.parse(window.render_game_to_text()).snapshot);
  await page.evaluate(()=>document.fonts.ready);
};
const inject=async(page,preset)=>{
  await page.getByRole('button',{name:'Introduce a change',exact:true}).click();
  await page.locator(`[data-preset="${preset}"]`).click();
  await page.waitForTimeout(80);
};
try{
  for(const width of [390,768,1440]){
    const context=await browser.newContext({viewport:{width,height:width===390?844:1000},reducedMotion:'reduce',hasTouch:width===390});
    const page=await context.newPage(),errors=[],requests=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>requests.push(r.url()));
    await open(page);
    assert.equal((await read(page)).team.length,6);
    assert.equal((await read(page)).day,0);
    const start=page.locator('#start-btn');
    const rect=await start.boundingBox();
    assert(rect&&rect.y>=0&&rect.y+rect.height<=(width===390?844:1000),'Primary control must be visible on entry');
    assert.equal(await overflow(page),false);
    await page.screenshot({path:resolve(out,`${width}-ready.png`),fullPage:true});
    await page.locator('.rm-person').filter({hasText:'Sarah'}).click();
    await page.getByRole('dialog').waitFor();
    assert.match(await page.getByRole('dialog').innerText(),/Sarah/);
    await page.keyboard.press('Escape');
    await page.locator('.rm-task-card').first().click();
    await page.getByRole('dialog').waitFor();
    assert.match(await page.getByRole('dialog').innerText(),/Product brief|Service architecture/);
    await page.keyboard.press('Escape');
    await start.click();await inject(page,'sarah-leave');
    assert((await read(page)).injections.includes('sarah-leave'));
    await step(page,60000);
    let s=await read(page);assert.equal(s.day,30);
    assert(s.memoryOps.some(op=>op.op==='archive'));
    await page.screenshot({path:resolve(out,`${width}-archive.png`),fullPage:true});
    await step(page,2000);s=await read(page);assert.equal(s.day,31);
    assert(s.checks.some(c=>c.verdict==='divergence'));
    await page.getByRole('button',{name:/^Pause(?: quarter)?$/}).click();
    await step(page,10000);assert.equal((await read(page)).day,31,'Pause must freeze the simulation');
    await page.screenshot({path:resolve(out,`${width}-divergence.png`),fullPage:true});
    await page.getByRole('button',{name:/^Resume(?: quarter)?$/}).click();
    await step(page,2000);s=await read(page);assert.equal(s.day,32);
    assert(s.memoryOps.some(op=>op.op==='restore'));
    assert(s.metrics.restores>0);
    await page.getByRole('button',{name:/Memory X-ray/i}).first().click();
    const dialog=page.getByRole('dialog');await dialog.waitFor();
    assert.match(await dialog.innerText(),/Sarah|availability/i);
    await page.locator('.rm-fact').filter({hasText:'fact-sarah-availability'}).locator('summary').click();
    assert.match(await dialog.innerText(),/player preset/);
    await page.screenshot({path:resolve(out,`${width}-memory.png`),fullPage:true});
    await page.keyboard.press('Escape');assert.equal(await dialog.count(),0);
    await step(page,56000);s=await read(page);assert.equal(s.status,'completed');
    assert(s.outcome);assert.equal(s.receipts.length,0,'Fixtures cannot create sponsor receipts');
    assert.equal(await overflow(page),false);
    await page.screenshot({path:resolve(out,`${width}-outcome.png`),fullPage:true});
    await page.getByRole('button',{name:'Restart quarter',exact:true}).click();
    await page.getByRole('button',{name:'Reset without starting',exact:true}).click();
    assert.equal((await read(page)).day,0);
    assert.equal(errors.length,0,errors.join('\n'));
    assert.equal(requests.filter(u=>!u.startsWith(base)&&!u.startsWith('data:')).length,0);
    assert.equal(requests.filter(u=>u.startsWith(`${base}/api/`)).length,0,'Public game must not call APIs');
    report.checks.push({width,startVisible:true,personAndTaskDetails:true,sourceEvidence:true,intervention:true,archiveDivergenceRestore:true,pause:true,restart:true,overflow:false,reducedMotion:true,pageErrors:errors.length,publicApiCalls:0});
    await context.close();
  }
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await open(page);
  await page.getByRole('checkbox',{name:/Memory stress test/i}).uncheck();
  await page.locator('#start-btn').click();await step(page,64000);
  let s=await read(page);assert.equal(s.stressTest,false);assert.equal(s.metrics.restores,0);
  assert(s.decisions.some(d=>d.state==='prevented'));
  await page.screenshot({path:resolve(out,'retained-fact.png'),fullPage:true});
  report.checks.push({normalRun:'Fact retained, invalid assignment prevented, zero restores'});
  await open(page);await page.locator('#start-btn').click();await inject(page,'deadline-shift');await step(page,120000);
  s=await read(page);assert.equal(s.status,'completed');assert.equal(s.outcome.success,false,'Shortening the deadline must not be a fixed win');
  await page.screenshot({path:resolve(out,'missed-deadline.png'),fullPage:true});
  report.checks.push({changedDeadline:'Actual missed-target outcome, no guaranteed victory'});
  await open(page);await page.locator('#start-btn').click();await inject(page,'dependency-delay');await step(page,120000);
  s=await read(page);assert.equal(s.outcome.success,false);
  assert(s.tasks.some(t=>t.status!=='done'));
  assert(s.facts.some(f=>f.id==='fact-dependency-delay'));
  report.checks.push({dependencyDelay:'Missing dependency blocks downstream work and remains in evidence'});
  await page.goto(`${base}/demo/table`);await page.getByRole('region',{name:'Interactive team table'}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('stage'),'1');
  await page.keyboard.press('Tab');assert(await page.evaluate(()=>document.activeElement!==document.body));
  await page.goto(`${base}/demo/remaster/app`);await page.waitForTimeout(700);
  const status=await (await page.request.get(`${base}/api/remaster/status`)).json();
  assert.equal(status.status,'BLOCKED');
  const liveStart=page.locator('#start-btn');if(await liveStart.count()&&await liveStart.isEnabled())await liveStart.click();
  await page.waitForTimeout(300);
  const live=await read(page);assert.equal(live,null,'Blocked live runtime must not show fixture state');
  assert.match(await page.locator('body').innerText(),/blocked|not connected|unavailable|not configured/i);
  await page.screenshot({path:resolve(out,'live-blocked.png'),fullPage:true});
  await page.goto(`${base}/acquisition`);await page.locator('.page-heading h1').waitFor();
  await page.goto(`${base}/acquisition/app`);await page.getByRole('button',{name:'Open workspace',exact:true}).waitFor();
  report.checks.push({legacyRoutes:'Presentation redirects to human workspace; REMaster and acquisition retained',live:'BLOCKED without fixture fallback',keyboardFocus:true});
  await page.close();
}catch(e){report.errors.push(e.message);throw e;}
finally{await browser.close();await writeFile(resolve(out,'browser-report.json'),JSON.stringify(report,null,2));}
console.log(JSON.stringify(report,null,2));
